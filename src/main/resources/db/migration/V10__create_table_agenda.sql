CREATE TABLE tb_agenda (
    id bigint GENERATED BY DEFAULT AS IDENTITY primary key,
    descricao varchar(150) not null,
    duracao time not null,
    funcionario_id bigint not null,
    especialidade_id bigint not null,
    sala varchar(10),
    created_at timestamp default now(),
    updated_at timestamp default now(),
    foreign key (funcionario_id) references tb_funcionario(id),
    foreign key (especialidade_id) references tb_especialidade(id)
);

alter table tb_agenda add column modalidade_convenio boolean default false;
alter table tb_agenda add column modalidade_particular boolean default false;
alter table tb_agenda add column valor_consulta_particular decimal(10,2);
